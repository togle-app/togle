const { app } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const { WindowsNotices } = require('./notices.cjs')
const { name, id, clsid, folder } = require('./identity.json')
const file = name => path.join(folder, name)
app.setName(name)
app.setPath('userData', file('profile'))
app.setAppUserModelId(id)
app.setToastActivatorCLSID(clsid)
app.disableHardwareAcceleration()
app.whenReady().then(async () => {
  const notices = new WindowsNotices(dest => fs.writeFileSync(file('destination'), JSON.stringify(dest)), (app, always) => fs.appendFileSync(file('calls'), app + ':' + always + '\n'))
  await notices.start()
  if (process.argv.includes('--post')) {
    const item = (key, kind, title, fields = {}) => ({ id: key + '#42', key, kind, title, agent: 'Codex', detailKind: 'words', detail: '', ...fields })
    const pending = item('codex:request', 'waiting', 'Build & verify', { detailKind: 'command', detail: 'npm test --secret fixture-secret' })
    const update = (meeting, finished) => notices.refresh({ notices: [pending], finished, waiting: 1 }, { front: false, meeting, notices: true, finished: true, notificationPreviews: true }, () => true)
    update(false, [])
    update(false, [item('codex:result', 'done', 'Draft handoff', { result: "Couldn't save the edit to design.html. The revised instructions are in a working copy." })])
    update(true, [item('codex:a', 'done', 'Update docs', { result: 'Updated the guide.' })])
    update(true, [item('codex:b', 'done', 'Check <installer>', { result: 'All 12 checks passed.' })])
    update(false, [])
    notices.offerCall('zoom')
    fs.writeFileSync(file('ready'), 'yes')
  } else fs.writeFileSync(file('cold'), 'yes')
  setInterval(() => { if (fs.existsSync(file('stop'))) { notices.stop(); app.quit() } }, 100)
}).catch(error => { fs.writeFileSync(file('error'), error.stack); app.exit(1) })
