const assert = require('node:assert/strict')

module.exports = async ({ app, windows, main, js, wait, find, invoke, item, profile, icon, BrowserWindow }) => {
  const { posted, dialogs } = windows
  const start = (title, prompt) => invoke('runners:start', { runner: 'hermes', folder: profile, prompt, title })
  const waiting = key => find(async () => (await invoke('runners:list')).find(task => task.key === key && task.pending.length), 'agent approval')
  const finish = async key => {
    const task = await waiting(key)
    await invoke('runners:answer', key, task.pending[0].id, 'allow-once')
    await wait(async () => (await invoke('runners:list')).find(task => task.key === key)?.state === 'idle', 'task result')
  }
  main.isVisible = () => true
  main.isFocused = () => true
  const first = await start('Review release & notes', 'run privatewords')
  await waiting(first.key)
  assert.equal(posted.length, 0, 'quiet while Togle is in front')
  main.isFocused = () => false
  main.emit('blur')
  await wait(() => posted.length === 1, 'first native alert')
  const alert = posted[0]
  assert.match(alert.options.toastXml, /Review request/)
  assert.match(alert.options.toastXml, /Hermes needs input · Review release &amp; notes/)
  assert.match(alert.options.toastXml, /Approve running echo\?/)
  assert.doesNotMatch(alert.options.toastXml, /privatewords|Allow once|Refuse|\.txt/i)
  for (let i = 0; i < 3; i++) main.emit('blur')
  await invoke('runners:list')
  assert.equal(posted.length, 1)
  assert.ok(icon.tooltip.includes('1 task waiting'))
  alert.emit('close', { reason: 'timedOut' })
  alert.click()
  await wait(() => js(main, "document.querySelector('.task-title h2')?.textContent.includes('Review release & notes')"), 'click opens exact task')
  assert.equal((await waiting(first.key)).pending.length, 1, 'opening the task leaves the decision pending')
  await invoke('settings:update', { tasks: { notificationPreviews: false } })
  const second = await start('Fix installer', 'run different')
  await wait(() => posted.length === 2, 'second independent alert')
  assert.match(posted[1].options.toastXml, /A command needs approval/)
  assert.doesNotMatch(posted[1].options.toastXml, /Fix installer|different|Hermes|echo/)
  posted[1].emit('close', { reason: 'userCanceled' })
  main.emit('blur')
  assert.equal(posted.length, 2, 'dismissed request stays dismissed')
  assert.equal((await waiting(second.key)).pending.length, 1)
  await invoke('session:listening', true)
  await finish(first.key)
  await finish(second.key)
  assert.equal(posted.length, 2, 'quiet during meeting')
  await invoke('settings:update', { tasks: { notificationPreviews: true } })
  await invoke('session:listening', false)
  await wait(() => posted.length === 3, 'summary')
  const summary = posted[2]
  assert.match(summary.options.toastXml, /2 tasks finished/)
  assert.match(summary.options.toastXml, /Hermes · Review release &amp; notes — Ran echo\./)
  assert.match(summary.options.toastXml, /Hermes · Fix installer — Ran echo\./)
  assert.doesNotMatch(summary.options.toastXml, /privatewords|\.txt/i)
  assert.match(summary.options.toastXml, /silent="true"/)
  summary.click()
  await wait(() => js(main, "document.querySelector('[aria-label=\"Task results\"]')?.innerText.includes('Fix installer')"), 'both results')
  assert.deepEqual(await js(main, "Array.from(document.querySelectorAll('.notification-results .link'), b => b.textContent).sort()"), ['Fix installer', 'Review release & notes'])
  await js(main, "Array.from(document.querySelectorAll('.notification-results .link')).find(b => b.textContent==='Fix installer').click()")
  await wait(() => js(main, "document.querySelector('.task-title h2')?.textContent.includes('Fix installer')"), 'second result opens')
  process.env.TOGLE_TEST_FRONT_PROGRAM = 'C:\\Program Files\\Microsoft VS Code\\Code.exe'
  await invoke('dev:hotkey', 'task')
  await wait(() => js(main, "document.querySelector('[aria-label=\"Shortcut conflict\"]')?.textContent.includes('F10')"), 'in-app shortcut offer')
  await js(main, "Array.from(document.querySelectorAll('[aria-label=\"Shortcut conflict\"] button')).find(b => b.textContent==='Change shortcut').click()")
  await wait(() => js(main, "!!document.getElementById('settings-keys') && !document.querySelector('[aria-label=\"Shortcut conflict\"]')"), 'shortcut settings')
  await invoke('dev:hotkey', 'task')
  assert.equal((await invoke('settings:get')).keysOffer.key, '')
  assert.ok(!BrowserWindow.getAllWindows().some(win => /surface=(notice|keysnotice|callnotice)/.test(win.webContents.getURL())))
  await invoke('settings:update', { tasks: { notices: false } })
  const last = await start('Still working', 'run pending')
  await waiting(last.key)
  await wait(() => icon.tooltip.includes('1 task waiting'), 'pending task')
  assert.equal(posted.length, 3, 'disabled request alerts still count in the tray')
  await invoke('settings:update', { tasks: { notices: true }, window: { keepOutOfCaptures: true } })
  await wait(() => posted.length === 4, 're-enabled request alert')
  assert.match(posted[3].options.toastXml, /A command needs approval/)
  assert.doesNotMatch(posted[3].options.toastXml, /Still working|Hermes|echo/)
  item('Quit Togle').click()
  item('Quit Togle').click()
  await wait(() => dialogs.length === 1, 'one native confirmation')
  const confirm = dialogs[0]
  assert.equal(confirm.options.buttons[confirm.options.defaultId], 'Keep working')
  assert.equal(confirm.options.cancelId, confirm.options.defaultId)
  assert.match(confirm.options.detail, /Still working/)
  confirm.answer(0)
  await new Promise(resolve => setImmediate(resolve))
  assert.equal(main.isDestroyed(), false)
  item('Quit Togle').click()
  await wait(() => dialogs.length === 2, 'confirm again')
  const quit = new Promise(resolve => app.once('will-quit', resolve))
  dialogs[1].answer(1)
  await quit
  console.log('WINDOWS NOTICE PASS: private alerts, deduplication, dismissal, deep links, meeting results, in-app shortcuts and native quit confirmation')
}
