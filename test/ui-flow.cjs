// No real account, microphone, downloads or model requests are used.
const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
// Hosted Intel Macs have no usable EGL display; these deterministic UI fixtures
// exercise software rendering, as the other Electron integration suites do.
app.disableHardwareAcceleration()

const project = path.resolve(__dirname, '..')
const artifacts = path.join(__dirname, '.work', 'ui')
const data = path.join(artifacts, 'data-' + process.pid)
fs.mkdirSync(data, { recursive: true })
app.setPath('userData', data)
process.env.TOGLE_TEST_USER_DATA = data
