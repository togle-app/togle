let checkpoint = 'startup'
const timeout = setTimeout(() => { console.error('UI checks timed out at ' + checkpoint); app.exit(1) }, 180000)

async function open(T, agent, scenario, width = 640) {
  checkpoint = scenario + ' at ' + width + 'px'
  const settings = structuredClone(T.getSettings())
  const readyAudio = !['account', 'speech'].includes(scenario)
  settings.provider = scenario === 'account' ? 'chatgpt' : 'claude'
  settings.claude.auth = 'subscription'
  settings.transcription.accountId = ['account', 'speech'].includes(scenario) ? 'chatgpt-default' : 'claude-default'
  settings.transcription.language = 'en'
  settings.activeAgentId = agent.id
  if (scenario === 'private-call') settings.assist.rememberCalls = false
  settings.transcription.me = settings.transcription.them = readyAudio ? 'local' : 'chatgpt'
  const names = [...fs.readFileSync(path.join(project, 'src/shared/api.ts'), 'utf8').matchAll(/^  (\w+)\(/gm)].map(m => m[1])
  const fixtureAgents = [agent, { ...agent, id: agent.id + '-support', name: 'Support' }]
  if (scenario === 'training') fixtureAgents[0] = { ...agent,
    memory: ['The deployment branch is main.'],
    skills: [{ id: 'incident-skill', name: 'Incident response', when: 'Someone reports a production incident', how: '- Establish the impact.\n- Ask [the owner](https://example.com/owner).', purpose: 'assistance', origin: 'call', createdAt: Date.now(), updatedAt: Date.now(), uses: 3 }, { id: 'legacy-tdd', name: 'Test-first and TDD discussions', when: 'The team discusses testing', how: '- QA prepares test cases before development.', origin: 'call', createdAt: Date.now(), updatedAt: Date.now() }],
    answers: [{ id: 'release-answer', question: 'Where is the release guide?', answer: 'Read [the release guide](https://example.com/release).', origin: 'manual', createdAt: Date.now() }],
    knowledge: [{ id: 'release-doc', name: 'Release process', kind: 'web', source: 'https://example.com/release', status: 'ready', digest: 'Confirm the release owner before deploying.', addedAt: Date.now(), chars: 200 }]
  }
  if (scenario === 'many-agents') fixtureAgents.push(...Array.from({ length: 12 }, (_, index) => ({ ...agent, id: 'specialist-' + index, name: 'Specialist ' + (index + 1) })))
  const fixture = JSON.stringify({ settings, names, agents: fixtureAgents, scenario, readyAudio, templates: T.AGENT_TEMPLATES, claudeSpeechLanguages: [...T.CLAUDE_SPEECH_LANGUAGES], richText: scenario === 'rich-text' ? require('./rich-text-fixtures.cjs').reply : undefined })
  const preload = path.join(artifacts, 'preload-' + scenario + '-' + width + '.cjs')
  fs.writeFileSync(preload, 'const fixture=' + fixture + '\nrequire(' + JSON.stringify(path.join(__dirname, 'ui-fixture.cjs')) + ')(fixture)')
  const errors = []
  const remoteRequests = []
  const window = new BrowserWindow({
    show: false, width, height: 850,
    webPreferences: { preload, sandbox: false, backgroundThrottling: false, offscreen: true }
  })
  window.webContents.on('console-message', (event) => { if (event.level === 'error') errors.push(event.message) })
  if (scenario === 'rich-text') window.webContents.session.webRequest.onBeforeRequest({ urls: ['https://never-fetch.example.invalid/*'] }, (request, callback) => { remoteRequests.push(request.url); callback({ cancel: true }) })
  const evaluate = async code => {
    checkpoint = scenario + ': ' + code.slice(0, 180)
    try { return await window.webContents.executeJavaScript(code) }
    catch (error) { throw new Error(error.message + '\nWhile running: ' + code + '\n' + errors.join('\n')) }
  }
  const paint = async () => {
    // A hidden offscreen renderer can stop receiving animation frames on macOS.
    // Yield to rendering without letting the fixture wait forever for a frame.
    await evaluate('new Promise(resolve=>{const timer=setTimeout(resolve,100);requestAnimationFrame(()=>requestAnimationFrame(()=>{clearTimeout(timer);resolve()}))})')
    await new Promise(resolve => setTimeout(resolve, 30))
  }
  const wait = async code => {
    for (let n = 0; n < 100; n++) {
      if (await evaluate(code)) return paint()
      await new Promise(resolve => setTimeout(resolve, 30))
    }
    const diagnostics = { scenario, width, condition: code, errors, detail: await evaluate("({text:document.body.innerText,visibility:document.visibilityState,listening:document.querySelector('button.listen')?.textContent,calls:window.togleUITest?.calls().slice(-15)})").catch(error => ({ error: error.message })) }
    fs.writeFileSync(path.join(artifacts, 'failure.json'), JSON.stringify(diagnostics, null, 2))
    try { fs.writeFileSync(path.join(artifacts, 'failure.png'), (await window.webContents.capturePage()).toPNG()) } catch {}
    throw new Error('UI did not reach: ' + code + '\n' + JSON.stringify(diagnostics, null, 2))
  }
  const click = async (selector, label) => {
    await evaluate("(()=>{const button=[...document.querySelectorAll(" + JSON.stringify(selector) + ")].find(e=>e.getClientRects().length&&(e.textContent.trim()===" + JSON.stringify(label) + "||e.getAttribute('aria-label')===" + JSON.stringify(label) + "));if(!button)throw new Error('Missing button: '+" + JSON.stringify(label) + ");button.click()})()")
    await paint()
    // These scenarios deliberately exercise audio-only calls. Screen scenarios choose their source explicitly.
    if (selector === 'button.listen' && ['Start call', 'Resume call'].includes(label) && !scenario.startsWith('screen')) {
      await wait("!!document.querySelector('.monitor-picker')||!!document.querySelector('.settings')||document.querySelector('button.listen')?.textContent.includes('End call')")
      if (await evaluate("!!document.querySelector('.monitor-picker')")) await click('.monitor-picker button', 'Start with audio only')
    }
  }
  const key = async key => {
    await evaluate("document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:" + JSON.stringify(key) + ",bubbles:true,cancelable:true}))")
    await paint()
  }
  const capture = async name => {
    await paint()
    fs.writeFileSync(path.join(artifacts, name + '.png'), (await window.webContents.capturePage()).toPNG())
  }
  await window.loadFile(process.env.TOGLE_UI_RENDERER || path.join(project, 'out/renderer/index.html'))
  await wait("!!document.querySelector('button.listen')&&!document.querySelector('button.listen').disabled")
  return { window, errors, evaluate, paint, wait, click, key, capture, remoteRequests }
}

async function fits(ui, selector) {
  assert.ok(await ui.evaluate("(()=>{const el=document.querySelector(" + JSON.stringify(selector) + ");if(!el)return false;const r=el.getBoundingClientRect();return r.width>0&&r.left>=7&&r.top>=7&&r.right<=innerWidth-7&&r.bottom<=innerHeight-7&&el.scrollWidth<=el.clientWidth+1})()"), selector + ' must fit the window without horizontal clipping')
}

/** As wide as the window allows, with nothing cut off at the side (a long settings section may scroll). */
async function fitsWidth(ui, selector) {
  assert.ok(await ui.evaluate("(()=>{const el=document.querySelector(" + JSON.stringify(selector) + ");if(!el)return false;const r=el.getBoundingClientRect();return r.width>0&&r.left>=0&&r.right<=innerWidth&&el.scrollWidth<=el.clientWidth+1&&[...el.querySelectorAll('button,input,select,span')].every(child=>{const c=child.getBoundingClientRect();return !c.width||c.left>=r.left-1&&c.right<=r.right+1})})()"), selector + ' must fit the window width')
}

async function fill(ui, selector, value) {
  await ui.evaluate("(()=>{const el=document.querySelector(" + JSON.stringify(selector) + ");const proto=el.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,'value').set.call(el," + JSON.stringify(value) + ");el.dispatchEvent(new Event('input',{bubbles:true}))})()")
  await ui.paint()
}

async function checkTogleMicrophone(T, agent) {
  const section = '#settings-microphone'
  const status = "document.querySelector('#settings-microphone .microphone-status')?.textContent"
  const calledWith = (flow, name) => flow.evaluate('window.togleUITest.calls().filter(c=>c.name===' + JSON.stringify(name) + ').map(c=>c.args)')
  for (const width of [400, 1100]) {
    // Not installed: what it is, and a way to get it. Turning it on for calls needs it installed.
    const missing = await open(T, agent, 'default', width)
    await missing.click('.sidebar-settings', 'Settings')
    await missing.wait("!!document.querySelector('" + section + "')")
    await missing.wait(status + "==='Not installed'")
    assert.equal(await missing.evaluate("document.querySelectorAll('" + section + " [role=switch]')[0].disabled"), true, 'turning it on for calls waits for an installed Togle Microphone')
    await missing.evaluate("document.querySelector('" + section + "').scrollIntoView({block:'start'})")
    await fitsWidth(missing, section)
    await missing.capture('togle-microphone-missing-' + width)
    await missing.click(section + ' button', 'Get Togle Microphone')
    assert.deepEqual(await calledWith(missing, 'openMicrophonePage'), [['settings']], 'the page opens tagged with where it came from')
    assert.deepEqual(missing.errors, [])
    missing.window.destroy()

    // Installed and running, off: it turns on and off from Settings, and shows what it cleans.
    const flow = await open(T, agent, 'togle-microphone', width)
    await flow.click('.sidebar-settings', 'Settings')
    await flow.wait(status + "==='Off'")
    assert.equal(await flow.evaluate("document.querySelectorAll('" + section + " [role=switch]')[0].checked"), true, 'turning it on for calls is the default')
    await flow.click(section + ' button', 'Turn on')
    await flow.wait(status + "==='On · cleaning USB Headset'")
    await flow.evaluate("document.querySelector('" + section + "').scrollIntoView({block:'start'})")
    await fitsWidth(flow, section)
    await flow.capture('togle-microphone-on-' + width)
    await flow.click(section + ' button', 'Turn off')
    await flow.wait(status + "==='Off'")
    await flow.click(section + ' button', 'Open')
    assert.deepEqual(await calledWith(flow, 'showMicrophone'), [[null]], 'its own window opens (no page: settings)')
    // A call turns it on first, and the call strip says so.
    await flow.click('.sidebar-settings', 'Settings')
    await flow.evaluate("document.querySelector('.settings .page-head button.icon')?.click()")
    await flow.paint()
    await flow.click('button.listen', 'Start call')
    await flow.wait("document.querySelector('button.listen')?.textContent.includes('End call')")
    assert.ok((await calledWith(flow, 'prepareCallMicrophone')).length >= 1, 'the call asks Togle Microphone to be on before the audio opens')
    await flow.wait("document.querySelector('.clean-mic-chip.on')?.textContent==='Clean mic'")
    await flow.capture('togle-microphone-call-' + width)
    await flow.click('button.listen', 'End call')
    assert.deepEqual(flow.errors, [])
    flow.window.destroy()
  }

  // Signed out of Togle Microphone: Settings and the call strip ask to sign in to it (in its own window), and a call
  // leaves it alone.
  for (const width of [400, 1100]) {
    const flow = await open(T, agent, 'togle-microphone-signed-out', width)
    await flow.click('.sidebar-settings', 'Settings')
    await flow.wait(status + "==='Signed out · sign in to use it'")
    assert.equal(await flow.evaluate("[...document.querySelectorAll('" + section + " button')].some(b=>['Turn on','Open'].includes(b.textContent.trim()))"), false, 'nothing to turn on, and one way to open it')
    await flow.evaluate("document.querySelector('" + section + "').scrollIntoView({block:'start'})")
    await fitsWidth(flow, section)
    await flow.capture('togle-microphone-signed-out-' + width)
    await flow.click(section + ' button', 'Sign in')
    assert.deepEqual(await calledWith(flow, 'showMicrophone'), [[null]], 'its window opens, where the sign-in is')
    await flow.evaluate("document.querySelector('.settings .page-head button.icon')?.click()")
    await flow.paint()
    await flow.click('button.listen', 'Start call')
    await flow.wait("document.querySelector('button.listen')?.textContent.includes('End call')")
    await flow.wait("document.querySelector('.clean-mic-chip')?.textContent.trim()==='Clean mic · Sign in'")
    await flow.capture('togle-microphone-signed-out-call-' + width)
    await flow.click('.clean-mic-chip', 'Clean mic · Sign in')
    assert.equal((await calledWith(flow, 'showMicrophone')).length, 2, 'the chip opens it too')
    assert.deepEqual(await calledWith(flow, 'turnOnMicrophone'), [], 'never asked to turn on while signed out')
    await flow.click('button.listen', 'End call')
    assert.deepEqual(flow.errors, [])
    flow.window.destroy()
  }

  // A noisy call: after it, what the microphone picked up, a way to hear it, the page, and both ways to stop it.
  for (const [width, choice] of [[400, 'Get Togle Microphone'], [1100, 'Don’t show this again']]) {
    const flow = await open(T, agent, 'noisy-call', width)
    await flow.click('button.listen', 'Start call')
    await flow.wait("document.querySelector('button.listen')?.textContent.includes('End call')")
    assert.equal(await flow.evaluate("!!document.querySelector('.microphone-suggestion')"), false, 'nothing is suggested during a call')
    await flow.click('button.listen', 'End call')
    await flow.wait("!!document.querySelector('.microphone-suggestion')")
    const text = await flow.evaluate("document.querySelector('.microphone-suggestion').textContent")
    assert.ok(text.includes('picked up background noise') && text.includes('2 min 42 s') && text.includes('41 short sounds'), text)
    for (const label of ['Play what it picked up', 'Get Togle Microphone', 'Not now', 'Don’t show this again']) assert.ok(await flow.evaluate("[...document.querySelectorAll('.microphone-suggestion button')].some(b=>b.textContent.trim()===" + JSON.stringify(label) + ")"), label)
    await fits(flow, '.microphone-suggestion')
    await flow.capture('microphone-suggestion-' + width)
    const sent = (await calledWith(flow, 'noiseMeasured'))[0][0]
    assert.equal(sent.sample, undefined, 'the audio stays in the window: main gets levels only')
    await flow.click('.microphone-suggestion button', choice)
    await flow.wait("!document.querySelector('.microphone-suggestion')")
    if (choice === 'Get Togle Microphone') assert.deepEqual(await calledWith(flow, 'openMicrophonePage'), [['after-call']])
    else assert.ok((await calledWith(flow, 'updateSettings')).some(patch => patch?.microphone?.suggestions === false), 'Don’t show this again turns the suggestions off')
    assert.deepEqual(flow.errors, [])
    flow.window.destroy()
  }
  console.log('Togle Microphone: not installed, installed, on and off, turned on for a call, signed out of it, and the after-call noise suggestion passed at compact and wide sizes.')
}

